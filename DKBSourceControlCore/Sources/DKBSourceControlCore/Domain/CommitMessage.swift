import Foundation

/// The keywords `git-rule.md` allows in a commit header.
public enum CommitKeyword: String, CaseIterable, Sendable, Codable {
    case update = "Update"
    case create = "Create"
    case integration = "Integration"
    case remove = "Remove"
    case cleanCode = "Clean Code"
    case optimize = "Optimize"
    case fixBug = "Fix Bug"
    case checklist = "Checklist"
    case initial = "Initial"
    case release = "Release"
}

/// A commit message in the `git-rule.md` format, byte for byte:
///
///     + Keyword +
///      - Detail
///       + Sub-detail
///
/// No blank line after the header, exactly one space before "-", exactly
/// two before "+", one line per item, nothing after the last detail.
public struct CommitMessage: Sendable, Equatable, Codable {
    public struct Detail: Sendable, Equatable, Codable {
        public var text: String
        public var subs: [String]

        public init(_ text: String, subs: [String] = []) {
            self.text = text
            self.subs = subs
        }
    }

    public var keyword: CommitKeyword
    public var details: [Detail]

    public init(keyword: CommitKeyword, details: [Detail]) {
        self.keyword = keyword
        self.details = details
    }

    public func render() -> String {
        var lines = ["+ \(keyword.rawValue) +"]
        for detail in details {
            lines.append(" - \(detail.text)")
            lines += detail.subs.map { "  + \($0)" }
        }
        return lines.joined(separator: "\n")
    }

    /// Reads a message that follows the format (to amend or reuse it); nil
    /// for anything else, so the composer falls back to raw text.
    public static func parse(_ text: String) -> CommitMessage? {
        guard validate(text).allSatisfy({ !$0.isBlocking }) else { return nil }
        let lines = gitLines(text)
        guard let keyword = keyword(inHeader: lines[0]) else { return nil }
        var details: [Detail] = []
        for line in lines.dropFirst() {
            if line.hasPrefix(" - ") {
                details.append(Detail(String(line.dropFirst(3))))
            } else if line.hasPrefix("  + ") {
                details[details.count - 1].subs.append(String(line.dropFirst(4)))
            }
        }
        return CommitMessage(keyword: keyword, details: details)
    }

    /// Every problem with `text` as a commit message, in line order.
    /// Blocking issues disable Commit; the others are warnings (F4d).
    public static func validate(_ text: String) -> [CommitMessageIssue] {
        let lines = gitLines(text)
        var issues: [CommitMessageIssue] = []
        if keyword(inHeader: lines[0]) == nil { issues.append(.invalidHeader) }
        if lines.count < 2 { issues.append(.noDetails) }

        var sawDetail = false
        for (offset, line) in lines.enumerated() {
            let number = offset + 1
            if offset > 0 {
                if line.trimmingCharacters(in: .whitespaces).isEmpty {
                    issues.append(.blankLine(line: number))
                } else if line.hasPrefix(" - "), line.dropFirst(3).first?.isWhitespace == false {
                    sawDetail = true
                } else if line.hasPrefix("  + "), line.dropFirst(4).first?.isWhitespace == false {
                    if !sawDetail { issues.append(.subDetailBeforeDetail(line: number)) }
                } else {
                    issues.append(.malformedLine(line: number))
                }
            }
            if isAttribution(line) {
                issues.append(.aiAttribution(line: number))
            } else if mentionsAITool(line) {
                issues.append(.mentionsAITool(line: number))
            }
            if line.unicodeScalars.contains(where: { $0.properties.isAlphabetic && !$0.isASCII }) {
                issues.append(.nonEnglishText(line: number))
            }
            if line.count > maxLineLength { issues.append(.longLine(line: number)) }
        }
        return issues
    }

    static let maxLineLength = 200

    /// The lines git will store: `--cleanup=whitespace` drops leading and
    /// trailing blank lines and trailing spaces, so those never count
    /// against the format.
    static func gitLines(_ text: String) -> [String] {
        text.trimmingCharacters(in: .newlines).components(separatedBy: "\n").map { line in
            var line = Substring(line)
            while line.last?.isWhitespace == true { line.removeLast() }
            return String(line)
        }
    }

    static func keyword(inHeader line: String) -> CommitKeyword? {
        guard line.hasPrefix("+ "), line.hasSuffix(" +"), line.count > 4 else { return nil }
        return CommitKeyword(rawValue: String(line.dropFirst(2).dropLast(2)))
    }

    /// Trailers and footers AI tools add (git-rule: "no AI attribution of any
    /// kind"). These block. "Remove files generated by the build" doesn't:
    /// the attribution forms need an AI tool's name or address in the line.
    static func isAttribution(_ line: String) -> Bool {
        let lower = line.lowercased()
        if line.contains("🤖") || lower.contains("noreply@anthropic.com") { return true }
        let attributionForm = lower.hasPrefix("co-authored-by:") || lower.contains("generated with") || lower.contains("generated by")
        return attributionForm && mentionsAITool(line)
    }

    /// An AI tool's name in an ordinary line ("Integrate the Claude API") is
    /// usually about the code, so it only warns.
    static func mentionsAITool(_ line: String) -> Bool {
        let words = Set(line.lowercased().split { !$0.isLetter && !$0.isNumber }.map(String.init))
        return !words.isDisjoint(with: ["claude", "chatgpt", "copilot", "openai", "gemini", "anthropic"])
    }
}

public enum CommitMessageIssue: Sendable, Equatable {
    /// The first line isn't "+ Keyword +" with one of the ten keywords.
    case invalidHeader
    case noDetails
    case blankLine(line: Int)
    /// Not " - text" (one space) or "  + text" (two spaces).
    case malformedLine(line: Int)
    case subDetailBeforeDetail(line: Int)
    case aiAttribution(line: Int)
    case mentionsAITool(line: Int)
    /// git-rule: messages are English only. Names like "Cà Phê Tý Mập" are
    /// fine, hence a warning.
    case nonEnglishText(line: Int)
    case longLine(line: Int)

    public var isBlocking: Bool {
        switch self {
        case .invalidHeader, .noDetails, .blankLine, .malformedLine, .subDetailBeforeDetail, .aiAttribution: true
        case .mentionsAITool, .nonEnglishText, .longLine: false
        }
    }

    public var line: Int? {
        switch self {
        case .invalidHeader: 1
        case .noDetails: nil
        case .blankLine(let line), .malformedLine(let line), .subDetailBeforeDetail(let line), .aiAttribution(let line),
             .mentionsAITool(let line), .nonEnglishText(let line), .longLine(let line): line
        }
    }
}
