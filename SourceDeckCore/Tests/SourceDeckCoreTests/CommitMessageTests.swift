import Foundation
import Testing
@testable import SourceDeckCore

@Suite struct CommitMessageTests {
    /// The example in `dangkhoabach-Workspace/Agents/git-rule.md`, verbatim.
    static let gitRuleExample = """
        + Fix Bug +
         - Fix login not returning token
          + Add null check before serialization
          + Update response format
         - Fix timeout when calling third-party API
        """

    /// Messages in the git-rule format, as real commits use it.
    static let realMessages = [
        "+ Fix Bug +\n - README.md: the release date is 10/2024, not 09/2024",
        "+ Update +\n - CV portrait kept next to the CV, since the website no longer shows it\n  + CV-photo.webp: the portrait embedded in the CV PDF, removed from the website's public folder\n  + tools/build-cv.py: --photo defaults to CV-photo.webp and is skipped when the file is missing",
        "+ Initial +\n - Add build plan for SourceDeck, a native macOS Git client that replaces Sourcetree for daily work on this Mac\n  + Decisions D1-D21: git CLI backend instead of libgit2, self-signed certificate signing, GRDB storage, no sandbox, no force push or hard reset\n - Add .gitignore (Local.xcconfig, build output, Xcode user data)",
        "+ Checklist +\n - Complete Phase 0 PoC gate and record every measurement in the build plan\n  + status plus for-each-ref take 21-27 ms per repository, 87 ms for all 12 with four git processes at a time\n - Update decisions D5, D8 and D10 from the measurements\n  + D5 resolves PATH from the login shell once at launch with a fixed fallback",
        "+ Integration +\n - example-integration 0.4.0: example scenes in Home Assistant and Apple Home, deployed on the server\n  + scene.py: one scene entity per active scene of the gateway\n - config/homekit.yaml: expose scene.* on the bridge",
    ]

    @Test func renderMatchesTheGitRuleExampleByteForByte() {
        let message = CommitMessage(keyword: .fixBug, details: [
            .init("Fix login not returning token", subs: ["Add null check before serialization", "Update response format"]),
            .init("Fix timeout when calling third-party API"),
        ])
        #expect(message.render() == Self.gitRuleExample)
        #expect(Array(message.render().utf8) == Array(Self.gitRuleExample.utf8))
        #expect(CommitMessage.validate(message.render()).isEmpty)
    }

    @Test(arguments: realMessages)
    func realMessagesParseAndRenderBackUnchanged(text: String) throws {
        let message = try #require(CommitMessage.parse(text))
        #expect(message.render() == text)
    }

    @Test func allTenKeywordsAreAccepted() {
        #expect(CommitKeyword.allCases.count == 10)
        for keyword in CommitKeyword.allCases {
            #expect(CommitMessage.validate("+ \(keyword.rawValue) +\n - x").isEmpty, "\(keyword)")
        }
    }

    @Test(arguments: ["+ Feature +\n - x", "Update\n - x", "+Update+\n - x", "+ update +\n - x", "+ Update\n - x"])
    func invalidHeaderBlocks(text: String) {
        #expect(CommitMessage.validate(text).contains(.invalidHeader))
        #expect(CommitMessage.parse(text) == nil)
    }

    @Test func headerWithoutDetailsBlocks() {
        #expect(CommitMessage.validate("+ Update +") == [.noDetails])
    }

    @Test func blankLineAfterTheHeaderBlocks() {
        let issues = CommitMessage.validate("+ Update +\n\n - x")
        #expect(issues == [.blankLine(line: 2)])
        #expect(issues.allSatisfy { $0.isBlocking })
    }

    @Test(arguments: ["- no leading space", "  - two spaces", " -no space after", " + plus at one space",
                      "   + three spaces", "  +no space", " - ", "\t- tab"])
    func malformedLinesBlock(line: String) {
        #expect(CommitMessage.validate("+ Update +\n - ok\n\(line)") == [.malformedLine(line: 3)])
    }

    @Test func subDetailBeforeAnyDetailBlocks() {
        #expect(CommitMessage.validate("+ Update +\n  + orphan\n - x") == [.subDetailBeforeDetail(line: 2)])
    }

    @Test(arguments: [
        "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
        "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
        " - Generated with ChatGPT",
        " - Reviewed by noreply@anthropic.com",
    ])
    func aiAttributionBlocks(line: String) {
        #expect(CommitMessage.validate("+ Update +\n - x\n\(line)").contains { if case .aiAttribution = $0 { true } else { false } })
    }

    @Test(arguments: [" - Remove files generated by the build", "Co-Authored-By: Jane Doe <jane@example.com>"])
    func ordinaryLinesAreNotAttribution(line: String) {
        #expect(!CommitMessage.validate("+ Update +\n - x\n\(line)").contains { if case .aiAttribution = $0 { true } else { false } })
    }

    @Test func aiToolNameInADetailOnlyWarns() {
        let issues = CommitMessage.validate("+ Integration +\n - Integrate the Claude API for summaries")
        #expect(issues == [.mentionsAITool(line: 2)])
        #expect(!issues[0].isBlocking)
        #expect(CommitMessage.parse("+ Integration +\n - Integrate the Claude API for summaries") != nil)
    }

    @Test func vietnameseTextOnlyWarns() {
        let issues = CommitMessage.validate("+ Update +\n - Projects: Cà Phê Tý Mập POS")
        #expect(issues == [.nonEnglishText(line: 2)])
        #expect(!issues[0].isBlocking)
    }

    @Test func longLineOnlyWarns() {
        let issues = CommitMessage.validate("+ Update +\n - " + String(repeating: "a", count: 210))
        #expect(issues == [.longLine(line: 2)])
    }

    /// git stores the message without them (`--cleanup=whitespace`).
    @Test func trailingSpacesAndSurroundingBlankLinesAreFine() {
        #expect(CommitMessage.validate("\n+ Update +  \n - x \n  + y\t\n\n").isEmpty)
    }

    @Test func issueLineNumbers() {
        #expect(CommitMessageIssue.invalidHeader.line == 1)
        #expect(CommitMessageIssue.noDetails.line == nil)
        #expect(CommitMessageIssue.malformedLine(line: 4).line == 4)
    }
}
